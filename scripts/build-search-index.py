#!/usr/bin/env python3
"""Rebuild assets/search-index.js from the site's pages. Run after adding or editing a page:
   python3 scripts/build-search-index.py"""
import glob, html, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP = {"404.html"}

def text(s):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", s))).strip()

pages = []
for path in sorted(glob.glob(os.path.join(ROOT, "*.html"))):
    name = os.path.basename(path)
    if name in SKIP:
        continue
    s = open(path, encoding="utf-8").read()
    lang = (re.search(r'<html[^>]*lang="([a-z]+)', s) or [None, "en"])[1]
    title = text((re.search(r"(?s)<title>(.*?)</title>", s) or [None, name])[1])
    title = re.sub(r"\s*[|:]\s*BenefitMath$", "", title)
    desc = html.unescape((re.search(r'<meta name="description" content="([^"]*)"', s) or [None, ""])[1])
    m = re.search(r"<header\b", s)  # page content starts after the site menu
    body = s[m.start():] if m else s.split("<body", 1)[-1]
    body = re.sub(r"(?s)<(script|style|nav|footer|form|noscript|aside|template)\b[^>]*>.*?</\1>", " ", body)
    heads = [text(h) for h in re.findall(r"(?s)<h[1-3][^>]*>(.*?)</h[1-3]>", body)]
    pages.append({"u": "index.html" if name == "index.html" else name, "l": lang, "t": title,
                  "d": desc, "h": " · ".join(h for h in heads if h)[:600], "b": text(body)[:6000]})

out = os.path.join(ROOT, "assets", "search-index.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("/* Generated by scripts/build-search-index.py. Don't edit by hand. */\n")
    f.write("window.BM_SEARCH=" + json.dumps(pages, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"{len(pages)} pages -> {os.path.relpath(out, ROOT)} ({os.path.getsize(out)//1024} KB)")
